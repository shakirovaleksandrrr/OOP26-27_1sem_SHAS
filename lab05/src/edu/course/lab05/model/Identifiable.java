package edu.course.lab05.model;

/**
 * Обобщенный контракт для сущностей, обладающих уникальным идентификатором.
 *
 * @param <ID> тип первичного ключа / идентификатора
 */
public interface Identifiable<ID> {

    /**
     * Возвращает уникальный идентификатор сущности.
     *
     * @return идентификатор
     */
    ID getId();
}
